package com.school.student.domain.model;

/**
 * Enum representing the status of a student in the system.
 *
 * @author Backend Developer Agent
 * @version 1.0.0
 * @since 2026-02-03
 */
public enum StudentStatus {
    /**
     * Student is currently enrolled and active in the system
     */
    ACTIVE,

    /**
     * Student is inactive (graduated, withdrawn, or temporarily not enrolled)
     */
    INACTIVE
}
