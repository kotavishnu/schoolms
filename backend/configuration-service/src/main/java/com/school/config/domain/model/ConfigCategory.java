package com.school.config.domain.model;

/**
 * Configuration category enumeration.
 * Groups configuration settings by functional area.
 *
 * @author Backend Developer Agent
 * @version 1.0.0
 * @since 2026-02-04
 */
public enum ConfigCategory {
    /**
     * General school settings (name, code, logo, contact info)
     */
    GENERAL,

    /**
     * Academic settings (academic year, class capacity, grading system)
     */
    ACADEMIC,

    /**
     * Financial settings (fee structure, payment methods)
     */
    FINANCIAL
}
