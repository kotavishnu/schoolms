package com.school.sms.configuration.domain.model;

/**
 * Enum representing configuration categories.
 *
 * <p>Categories group related configuration settings:</p>
 * <ul>
 *   <li>GENERAL - General school settings (name, logo, etc.)</li>
 *   <li>ACADEMIC - Academic-related configurations (session dates, grade levels)</li>
 *   <li>FINANCIAL - Financial settings (fee structure, payment methods)</li>
 * </ul>
 *
 * @author School Management System Team
 * @version 1.0.0
 * @since 2025-12-06
 */
public enum Category {
    GENERAL,
    ACADEMIC,
    FINANCIAL
}
