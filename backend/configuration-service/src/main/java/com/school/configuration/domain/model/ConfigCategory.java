package com.school.configuration.domain.model;

/**
 * Configuration category enumeration.
 * Defines the categories for grouping configuration settings.
 */
public enum ConfigCategory {
    /**
     * General school-wide settings
     */
    GENERAL,

    /**
     * Academic-related settings (academic year, terms, etc.)
     */
    ACADEMIC,

    /**
     * Financial settings (fee structure, payment gateways, etc.)
     */
    FINANCIAL
}
